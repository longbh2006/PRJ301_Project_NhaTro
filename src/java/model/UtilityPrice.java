package model;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 *
 * @author Lenovo
 */
public class UtilityPrice {
        private int priceId;
        private BigDecimal electricPrice;
        private BigDecimal waterPrice;
        private BigDecimal serviceFeePerPerson;
        private  LocalDate effectiveFrom;
        private LocalDateTime createdAt;
        
        
    public int getPriceId() {
        return priceId;
    }

    public void setPriceId(int priceId) {
        this.priceId = priceId;
    }

    public BigDecimal getElectricPrice() {
        return electricPrice;
    }

    public void setElectricPrice(BigDecimal electricPrice) {
        this.electricPrice = electricPrice;
    }

    public BigDecimal getWaterPrice() {
        return waterPrice;
    }

    public void setWaterPrice(BigDecimal waterPrice) {
        this.waterPrice = waterPrice;
    }

    public BigDecimal getServiceFeePerPerson() {
        return serviceFeePerPerson;
    }

    public void setServiceFeePerPerson(BigDecimal serviceFeePerPerson) {
        this.serviceFeePerPerson = serviceFeePerPerson;
    }

    public LocalDate getEffectiveFrom() {
        return effectiveFrom;
    }

    public void setEffectiveFrom(LocalDate effectiveFrom) {
        this.effectiveFrom = effectiveFrom;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
        
        
}
